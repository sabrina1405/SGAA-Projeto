CREATE TYPE "modalidade_pagamento_enum" AS ENUM (
  'mensal',
  'semanal'
);

CREATE TYPE "status_entrega_enum" AS ENUM (
  'enviado',
  'avaliado',
  'entregue_com_atraso',
  'reenvio_solicitado'
);

CREATE TYPE "status_boleto_enum" AS ENUM (
  'pendente',
  'pago',
  'vencido',
  'cancelado',
  'estornado'
);

CREATE TYPE "status_aula_enum" AS ENUM (
  'agendada',
  'realizada',
  'cancelada'
);

CREATE TYPE "status_participacao_enum" AS ENUM (
  'ativa',
  'cancelada'
);

CREATE TYPE "tipo_usuario_enum" AS ENUM (
  'aluno',
  'professor'
);

CREATE TABLE "usuario" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nome_completo" varchar(100) NOT NULL,
  "email" varchar(80) UNIQUE NOT NULL,
  "senha" varchar(150), -- hash Argon2id; nulo até o primeiro acesso
  "tipo" tipo_usuario_enum NOT NULL, -- (professor, aluno)
  "versao_token" integer NOT NULL DEFAULT 0,
  "tentativas_login" integer NOT NULL DEFAULT 0,
  "bloqueado_ate" timestamptz,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz
);

CREATE TABLE "aluno" (
  "usuario_id" integer PRIMARY KEY,
  "data_nascimento" date NOT NULL,
  "possui_responsavel" boolean NOT NULL,
  "cpf" varchar(11) UNIQUE,
  "telefone" varchar(11),
  "responsavel_nome" varchar(100),
  "responsavel_cpf" varchar(11), -- sem UNIQUE: irmãos podem ter o mesmo responsável
  "responsavel_telefone" varchar(11),
  "modalidade" modalidade_pagamento_enum, -- ainda não implementado na API
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz,
  -- Menor de idade: só os dados do responsável. Maior: só os do aluno.
  CONSTRAINT "ck_aluno_dados_do_responsavel" CHECK (
    (possui_responsavel AND responsavel_nome IS NOT NULL
      AND responsavel_cpf IS NOT NULL AND responsavel_telefone IS NOT NULL
      AND cpf IS NULL AND telefone IS NULL)
    OR (NOT possui_responsavel AND cpf IS NOT NULL AND telefone IS NOT NULL
      AND responsavel_nome IS NULL AND responsavel_cpf IS NULL
      AND responsavel_telefone IS NULL)
  )
);

CREATE TABLE "professor" (
  "usuario_id" integer PRIMARY KEY,
  "cnpj" varchar(14) UNIQUE, -- sem máscara; aceita o formato alfanumérico
  "chave_pix" varchar(77) UNIQUE, -- CPF, CNPJ, e-mail, telefone ou aleatória
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz
);

-- Códigos de convite (primeiro acesso) e de redefinição de senha
CREATE TABLE "codigo_verificacao" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" integer NOT NULL,
  "codigo_hash" varchar(64) NOT NULL,
  "expira_em" timestamptz NOT NULL,
  "tentativas" integer NOT NULL DEFAULT 0,
  "usado_em" timestamptz,
  "criado_em" timestamptz NOT NULL DEFAULT (now())
);

-- Série semanal: as aulas apontam, em serie_id, para a primeira (que aponta para si)
CREATE TABLE "aula" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "professor_id" integer NOT NULL,
  "serie_id" integer,
  "reposicao_de_aula_id" integer,
  "titulo" varchar(75) NOT NULL,
  "descricao" varchar(150),
  "anotacoes" text, -- notas do professor; o aluno não vê
  "inicio" timestamptz NOT NULL,
  "fim" timestamptz NOT NULL,
  "status" status_aula_enum NOT NULL DEFAULT 'agendada',
  "motivo_cancelamento" varchar(150),
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz,
  CONSTRAINT "ck_aula_horario" CHECK (fim > inicio)
);

-- Participação do aluno; quem cancela fica com repor até a reposição (ou a dispensa)
CREATE TABLE "aula_aluno" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL, -- referência da fila de push
  "aula_id" integer NOT NULL,
  "aluno_id" integer NOT NULL,
  "status" status_participacao_enum NOT NULL DEFAULT 'ativa',
  "motivo_cancelamento" varchar(150),
  "cancelada_em" timestamptz,
  "repor" boolean NOT NULL DEFAULT false,
  "reposta_em_aula_id" integer,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  PRIMARY KEY ("aula_id", "aluno_id")
);

-- Grupos usados ao montar a aula; os alunos deles viram linhas de aula_aluno
CREATE TABLE "aula_grupo" (
  "aula_id" integer NOT NULL,
  "grupo_id" integer NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  PRIMARY KEY ("aula_id", "grupo_id")
);

CREATE TABLE "grupo" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "titulo" varchar(50) NOT NULL,
  "descricao" varchar(100),
  "professor_id" integer NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz
);

-- Um aluno pode estar em vários grupos; sair do grupo apaga a linha
CREATE TABLE "grupo_aluno" (
  "grupo_id" integer NOT NULL,
  "aluno_id" integer NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  PRIMARY KEY ("grupo_id", "aluno_id")
);

-- Painel fixo do professor, visível a todos os alunos; limpar preenche deletado_em
CREATE TABLE "recado_geral" (
  "professor_id" integer PRIMARY KEY,
  "conteudo" text NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz
);

-- Conteúdo em Markdown; sem data_fim, fica no mural até ser excluído
CREATE TABLE "recado" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "professor_id" integer NOT NULL,
  "conteudo" text NOT NULL,
  "data_inicio" date NOT NULL,
  "data_fim" date,
  "todos_alunos" boolean NOT NULL DEFAULT false,
  "todos_grupos" boolean NOT NULL DEFAULT false,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz,
  CONSTRAINT "ck_recado_periodo" CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- Destinatários avulsos; trocar os destinatários apaga as linhas
CREATE TABLE "recado_aluno" (
  "recado_id" integer NOT NULL,
  "aluno_id" integer NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  PRIMARY KEY ("recado_id", "aluno_id")
);

CREATE TABLE "recado_grupo" (
  "recado_id" integer NOT NULL,
  "grupo_id" integer NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  PRIMARY KEY ("recado_id", "grupo_id")
);

-- Aparelho que recebe push (ExpoPushToken); logout ou token inválido preenchem deletado_em
CREATE TABLE "dispositivo" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" integer NOT NULL,
  "token" varchar(255) UNIQUE NOT NULL,
  "plataforma" varchar(10),
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "atualizado_em" timestamptz NOT NULL DEFAULT (now()),
  "deletado_em" timestamptz
);

-- Fila de push; os destinatários são resolvidos na hora do envio pelo tipo e referencia_id
CREATE TABLE "notificacao" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tipo" varchar(30) NOT NULL,
  "referencia_id" integer NOT NULL,
